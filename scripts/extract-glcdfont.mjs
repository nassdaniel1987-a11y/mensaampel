// Copies the printable ASCII glyphs of the M5GFX default font (Adafruit GLCD 5x7, BSD licence) for the Dial simulation.
import {readFileSync,writeFileSync} from 'node:fs';
const source=readFileSync('vendor/M5GFX/src/lgfx/Fonts/glcdfont.h','utf8');
const bytes=[...source.slice(source.indexOf('font[]')).matchAll(/0x([0-9A-Fa-f]{2})/g)].map(m=>m[1].toLowerCase());
if(bytes.length<256*5)throw Error('Schrift unvollständig');
const ascii=bytes.slice(0x20*5,0x7f*5).join('');
writeFileSync('src/glcdfont.ts','// Generated by scripts/extract-glcdfont.mjs from M5GFX glcdfont.h (Copyright (c) 2012 Adafruit Industries, BSD licence, see licenses/Adafruit-GFX.txt).\n// Characters 0x20-0x7E, five column bytes each, least significant bit at the top.\nexport const glcdAscii=\''+ascii+'\';\n');
console.log('Dial-Schrift übernommen.');
